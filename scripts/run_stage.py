#!/usr/bin/env python3
"""Run one measurement stage on the GPU VM, driven entirely by runs/<id>/config.json.

Stages
    bench  -> `vllm bench latency` sweep (batch sizes x output lengths)       -> <run>/bench/
    nsys   -> Nsight Systems captures of scripts/prof_run.py (graphs / eager)   -> <run>/nsys/
    ncu    -> Nsight Compute: the plan generated by notebook 02 if present,
              otherwise a light metric-only sweep of the decode range           -> <run>/ncu/

Every stage is idempotent: an item whose output already exists is skipped, so after a
Spot preemption you restart the VM and run the same stage again.
Progress is written to <run>/status/<stage>.json so the notebook can show it.

Usage (on the VM, venv active, from the repo root):
    python scripts/run_stage.py bench --run-dir runs/<id>
    python scripts/run_stage.py nsys  --run-dir runs/<id> [--dry-run]
"""
import argparse
import json
import os
import shlex
import shutil
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PY = sys.executable

# vLLM boolean flags that need an explicit --no-<flag> to turn off
NEGATABLE = {"enable_prefix_caching", "enable_chunked_prefill", "async_scheduling"}


# ----------------------------------------------------------------------------- helpers
def vllm_cli_flags(vllm_args: dict) -> list:
    """Convert the notebook's vLLM argument dict into CLI flags for `vllm bench latency`."""
    out = []
    for k, v in vllm_args.items():
        flag = "--" + k.replace("_", "-")
        if v is None:
            continue
        if isinstance(v, bool):
            if v:
                out.append(flag)
            elif k in NEGATABLE:
                out.append("--no-" + k.replace("_", "-"))
            continue
        if isinstance(v, (dict, list)):
            out += [flag, json.dumps(v)]
        else:
            out += [flag, str(v)]
    return out


class Stage:
    def __init__(self, name, run_dir, dry_run=False):
        self.name, self.run, self.dry = name, Path(run_dir).resolve(), dry_run
        self.cfg = json.load(open(self.run / "config.json"))
        self.logs = self.run / "logs"
        self.status_dir = self.run / "status"
        for d in (self.logs, self.status_dir):
            d.mkdir(parents=True, exist_ok=True)
        self.items = []  # dicts: name, state (done/skipped/failed/running), seconds, optional
        self.env = dict(os.environ)
        self.env.update({k: str(v) for k, v in self.cfg.get("env", {}).items()})
        self.env.setdefault("VLLM_WORKER_MULTIPROC_METHOD", "spawn")

    def save_status(self, state="running"):
        doc = dict(stage=self.name, state=state, updated=time.time(), items=self.items)
        tmp = self.status_dir / f"{self.name}.json.tmp"
        tmp.write_text(json.dumps(doc, indent=1))
        tmp.replace(self.status_dir / f"{self.name}.json")

    def run_item(self, name, cmd, outputs, optional=False, env_extra=None, shell=False):
        """Run one command unless all its outputs already exist."""
        item = dict(name=name, optional=optional, state="running", seconds=0.0)
        self.items.append(item)
        if outputs and all(Path(o).exists() and Path(o).stat().st_size > 0 for o in outputs):
            item["state"] = "skipped (outputs exist)"
            print(f"[skip] {name}", flush=True)
            self.save_status()
            return True
        log = self.logs / f"{self.name}_{name}.log"
        printable = cmd if shell else " ".join(shlex.quote(c) for c in cmd)
        print(f"[run ] {name}\n       {printable}\n       log: {log.relative_to(self.run)}", flush=True)
        self.save_status()
        if self.dry:
            item["state"] = "dry-run"
            return True
        env = dict(self.env)
        env.update(env_extra or {})
        t0 = time.time()
        with open(log, "w") as fh:
            fh.write(f"$ {printable}\n\n")
            fh.flush()
            rc = subprocess.call(cmd, stdout=fh, stderr=subprocess.STDOUT, env=env, cwd=REPO, shell=shell)
        item["seconds"] = round(time.time() - t0, 1)
        ok = rc == 0 and all(Path(o).exists() for o in outputs)
        item["state"] = "done" if ok else f"failed (rc={rc})"
        if not ok:
            tail = "".join(open(log, errors="replace").readlines()[-25:])
            print(f"[FAIL] {name} rc={rc}\n{tail}", flush=True)
        self.save_status()
        return ok or optional

    def finish(self):
        failed = [i for i in self.items if i["state"].startswith("failed") and not i["optional"]]
        self.save_status("failed" if failed else "done")
        print(f"\nStage {self.name}: {len(self.items)} items, {len(failed)} failed", flush=True)
        return 1 if failed else 0


def gpu_idle_or_wait(timeout=120):
    """Refuse to start measuring while another process holds the GPU."""
    if not shutil.which("nvidia-smi"):
        return
    t0 = time.time()
    while True:
        out = subprocess.run(["nvidia-smi", "--query-compute-apps=pid,process_name,used_memory",
                              "--format=csv,noheader"], capture_output=True, text=True).stdout.strip()
        if not out:
            return
        if time.time() - t0 > timeout:
            raise SystemExit(f"GPU is busy, refusing to measure:\n{out}")
        print(f"waiting for GPU to be idle: {out}", flush=True)
        time.sleep(10)


def sudo_prefix(env_vars: dict):
    keep = {"PATH": os.environ.get("PATH", ""), "HOME": os.environ.get("HOME", ""),
            "HF_HOME": os.environ.get("HF_HOME", os.path.expanduser("~/.cache/huggingface"))}
    keep.update(env_vars)
    return ["sudo", "-E", "env"] + [f"{k}={v}" for k, v in keep.items()]


# ----------------------------------------------------------------------------- stages
def stage_bench(st: Stage):
    c, v = st.cfg["bench"], st.cfg["vllm"]
    out_dir = st.run / "bench"
    out_dir.mkdir(exist_ok=True)
    base = ["vllm", "bench", "latency"] + vllm_cli_flags(v) + st.cfg.get("vllm_extra_cli", [])
    L = st.cfg["workload"]["input_len"]
    for B in c["batch_sizes"]:
        for O in c["output_lens"]:
            js = out_dir / f"lat_b{B}_in{L}_out{O}.json"
            cmd = base + ["--batch-size", str(B), "--input-len", str(L), "--output-len", str(O),
                          "--num-iters-warmup", str(c["warmup_iters"]), "--num-iters", str(c["iters"]),
                          "--output-json", str(js)]
            st.run_item(f"b{B}_out{O}", cmd, [js])


def nsys_export(st: Stage, base: Path):
    rep, sql = base.with_suffix(".nsys-rep"), base.with_suffix(".sqlite")
    st.run_item(f"{base.name}_stats",
                ["nsys", "stats", "--report", "cuda_gpu_kern_sum,nvtx_sum", "--format", "csv",
                 "--force-export=true", "--output", str(base), str(rep)],
                [Path(f"{base}_cuda_gpu_kern_sum.csv")], optional=True)
    if not sql.exists():
        st.run_item(f"{base.name}_sqlite",
                    ["nsys", "export", "--type", "sqlite", "--force-overwrite=true", "--output", str(sql), str(rep)],
                    [sql])


def stage_nsys(st: Stage):
    c = st.cfg["nsys"]
    out_dir = st.run / "nsys"
    out_dir.mkdir(exist_ok=True)
    cfg_path = str(st.run / "config.json")
    common = ["nsys", "profile", "--force-overwrite=true", f"--trace={c['trace']}",
              "--cuda-graph-trace=node", "--trace-fork-before-exec=true",
              "--capture-range=cudaProfilerApi", "--capture-range-end=stop"] + c.get("extra_args", [])
    for B in c["batch_sizes"]:
        for mode in c["modes"]:
            base = out_dir / f"b{B}_{mode}"
            prog = [PY, str(REPO / "scripts/prof_run.py"), "--config", cfg_path,
                    "--batch", str(B), "--mode", mode, "--out", str(c["out_tokens"])]
            ok = st.run_item(f"b{B}_{mode}", common + ["-o", str(base)] + prog, [base.with_suffix(".nsys-rep")])
            if ok and not st.dry:
                nsys_export(st, base)
    if c.get("gpu_metrics"):
        # One extra B=1 graphs capture with GPU hardware counters sampled over time
        # (DRAM bandwidth, SM activity). Needs admin rights for counters -> sudo. Optional.
        B = c["batch_sizes"][0]
        base = out_dir / f"b{B}_graphs_gpumetrics"
        prog = [PY, str(REPO / "scripts/prof_run.py"), "--config", cfg_path,
                "--batch", str(B), "--mode", "graphs", "--out", str(c["out_tokens"])]
        cmd = sudo_prefix({"VLLM_ENABLE_V1_MULTIPROCESSING": "0", "VLLM_WORKER_MULTIPROC_METHOD": "spawn"}) + \
            common + ["--gpu-metrics-devices=0", f"--gpu-metrics-frequency={c.get('gpu_metrics_hz', 10000)}",
                      "-o", str(base)] + prog
        if st.run_item(f"b{B}_graphs_gpumetrics", cmd, [base.with_suffix(".nsys-rep")], optional=True) and not st.dry:
            subprocess.call(["sudo", "chown", "-R", os.environ.get("USER", "root"), str(out_dir)])
            nsys_export(st, base)


def stage_ncu(st: Stage):
    c = st.cfg["ncu"]
    out_dir = st.run / "ncu"
    out_dir.mkdir(exist_ok=True)
    plan = st.run / "ncu_plan" / "ncu_commands.sh"
    if c.get("use_plan", True) and plan.exists():
        # Plan generated by notebook 02 from the nsys traces (deep dives with computed --launch-skip)
        st.run_item("plan", f"bash {shlex.quote(str(plan))} {shlex.quote(str(st.run))} {shlex.quote(PY)}",
                    [], shell=True)
    else:
        cfg_path = str(st.run / "config.json")
        envs = {"VLLM_ENABLE_V1_MULTIPROCESSING": "0", "GMU": str(c["gmu"]), "MNS": str(c["mns"])}
        for B in c["sweep_batch_sizes"]:
            rep = out_dir / f"sweep_b{B}.ncu-rep"
            cmd = sudo_prefix(envs) + [
                "ncu", "--target-processes", "all", "--profile-from-start", "off", "--graph-profiling", "node",
                # one program run per metric pass; kernel replay would back up ~57 GB per kernel through host RAM
                "--replay-mode", "application", "--app-replay-mode", "relaxed",
                "--nvtx", "--nvtx-include", f"prefill_decode{c['out_tokens']}_b{B}/",
                "--metrics", ",".join(c["metrics"]), "--clock-control", "none",
                "-o", str(rep.with_suffix("")), "-f",
                PY, str(REPO / "scripts/prof_run.py"), "--config", cfg_path,
                "--batch", str(B), "--mode", "graphs", "--out", str(c["out_tokens"])]
            st.run_item(f"sweep_b{B}", cmd, [rep])
    if not st.dry:
        subprocess.call(["sudo", "chown", "-R", os.environ.get("USER", "root"), str(out_dir)])
        for rep in sorted(out_dir.glob("*.ncu-rep")):
            csv = rep.with_suffix(".csv")
            st.run_item(f"{rep.stem}_csv", f"ncu --import {shlex.quote(str(rep))} --csv --page raw > {shlex.quote(str(csv))}",
                        [csv], optional=True, shell=True)


STAGES = {"bench": stage_bench, "nsys": stage_nsys, "ncu": stage_ncu}

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("stage", choices=STAGES)
    ap.add_argument("--run-dir", required=True)
    ap.add_argument("--dry-run", action="store_true", help="print the commands, run nothing")
    a = ap.parse_args()
    st = Stage(a.stage, a.run_dir, a.dry_run)
    if not a.dry_run:
        gpu_idle_or_wait()
    st.save_status()
    STAGES[a.stage](st)
    sys.exit(st.finish())
